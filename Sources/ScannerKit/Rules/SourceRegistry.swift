import Foundation

public enum SourceRegistry {

    public struct Source: Decodable, Sendable, Hashable {
        public let key: String
        public let title: String
        public let homeURL: String
        public let urlPrefixes: [String]
        public let terms: String
        public let use: String
        public let role: String
    }

    private struct File: Decodable { let sources: [Source] }

    public static let all: [Source] =
        RuleData.decode(File.self, "taxonomy/sources.json").sources
            .sorted { $0.key < $1.key }

    public static func source(forURL url: String) -> Source? {
        all.first { $0.urlPrefixes.contains { url.hasPrefix($0) } }
    }

    public static func isRegistered(_ url: String) -> Bool { source(forURL: url) != nil }

    public static func citations(in rules: [Rule]) -> [(source: Source, urls: [String], ruleCount: Int)] {
        var urls: [String: Set<String>] = [:]
        var ruleIDs: [String: Set<String>] = [:]
        for rule in rules {
            for url in rule.citations {
                guard let s = source(forURL: url) else { continue }
                urls[s.key, default: []].insert(url)
                ruleIDs[s.key, default: []].insert(rule.id)
            }
        }
        return all.compactMap { s in
            guard let u = urls[s.key], !u.isEmpty else { return nil }
            return (source: s, urls: u.sorted(), ruleCount: ruleIDs[s.key]?.count ?? 0)
        }
    }
}

public extension SourceRegistry {

    static func markdownReport(rules: [Rule],
                               analyzerReferences: [String: [String]]) -> String {
        var ruleCount: [String: Int] = [:]
        var cited: Set<String> = []
        for rule in rules {
            for url in rule.citations {
                guard let s = source(forURL: url) else { continue }
                cited.insert(s.key)
                ruleCount[s.key, default: 0] += 1
            }
        }
        for (_, urls) in analyzerReferences {
            for url in urls {
                guard let s = source(forURL: url) else { continue }
                cited.insert(s.key)
                ruleCount[s.key, default: 0] += 1
            }
        }

        var out = ""
        out += "<!-- BEGIN GENERATED SOURCES -->\n"
        out += "<!-- Generated by `ISAT --sources-report`. Do not edit by hand:\n"
        out += "     add a source to Sources/ScannerKit/Resources/Rules/taxonomy/sources.json. -->\n\n"
        out += "| Source | How it's used | Citations | Terms |\n|---|---|---:|---|\n"
        for s in all {
            let n = ruleCount[s.key] ?? 0
            guard n > 0 || s.role != "rule-citation" else { continue }
            let name = s.homeURL.isEmpty ? s.title : "[\(s.title)](\(s.homeURL))"
            let count = n > 0 ? "\(n)" : "\u{2014}"
            out += "| \(name) | \(s.use) | \(count) | \(s.terms) |\n"
        }
        out += "\nCitations counts how many rule references resolve to that source. A source with "
        out += "\u{2014} is bound through the framework crosswalk, names a cluster, or is quoted as "
        out += "context rather than cited per rule.\n"
        out += "<!-- END GENERATED SOURCES -->\n"
        return out
    }

    static func bundledMarkdownReport() -> String {
        markdownReport(
            rules: RuleLoader.loadBundled().rules,
            analyzerReferences: Dictionary(uniqueKeysWithValues:
                Messages.knownRuleIDs.map { ($0, Messages.citations(forRuleID: $0)) }))
    }
}
